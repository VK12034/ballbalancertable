def run(_context):
    app = adsk.core.Application.get()
    ui = app.userInterface
    doc = None

    try:
        os.makedirs(OUT_DIR, exist_ok=True)
        log("ball balancer build")
        log("output: " + OUT_DIR)
        log("home crank {0:.1f} deg, platform z {1:.3f} mm".format(
            P["crank_home_angle"], HOME_Z))
        log("")

        doc = app.documents.add(adsk.core.DocumentTypes.FusionDesignDocumentType)
        design = adsk.fusion.Design.cast(app.activeProduct)
        design.designType = adsk.fusion.DesignTypes.ParametricDesignType
        design.unitsManager.distanceDisplayUnits = \
            adsk.fusion.DistanceUnits.MillimeterDistanceUnits
        # The root component takes its name from the document, so it only
        # becomes "BallBalancer" at saveAs time. Setting it here throws.
        root = design.rootComponent
        step("new design document", True, root.name)

        parameters(design)
        created, legs = assemble(root)

        check_kinematics()
        check_fastener_access(created)
        check_interference(design, root)
        check_actuator_travel(design, root, created, legs)
        assign_materials(app, root)
        collect_masses(root)

        save_views(app, OUT_DIR)
        export_all(design, root, OUT_DIR)

        # cloud save, so the design has a link. Optional: the f3d is the
        # real deliverable and does not need the hub.
        try:
            # app.data.activeProject is not always set when the script runs
            # with no project selected on Home, and asking it for a rootFolder
            # then throws InternalValidationError. Fall back to a named
            # project in the active hub.
            folder = None
            try:
                project = app.data.activeProject
                if project:
                    folder = project.rootFolder
            except Exception:
                folder = None

            if folder is None:
                projects = app.data.activeHub.dataProjects
                for i in range(projects.count):
                    candidate = projects.item(i)
                    if candidate.name == "Default Project":
                        folder = candidate.rootFolder
                        break
                if folder is None and projects.count > 0:
                    folder = projects.item(0).rootFolder

            if folder is None:
                raise RuntimeError("no writable project folder in this hub")

            # Re-running would otherwise pile up BallBalancer, BallBalancer
            # (1), BallBalancer (2) in the project. The f3d export is the
            # canonical artefact, so one cloud copy is enough.
            already = None
            try:
                for i in range(folder.dataFiles.count):
                    existing = folder.dataFiles.item(i)
                    if existing.name == "BallBalancer":
                        already = existing
                        break
            except Exception:
                already = None

            if already is not None:
                REPORT["fusion_doc"] = {
                    "name": already.name,
                    "id": already.id,
                    "version": already.versionNumber,
                    "note": "already in the project, not saved again",
                }
                step("cloud save", True,
                     "BallBalancer already present, v{0}".format(
                         already.versionNumber))
            elif doc.saveAs("BallBalancer", folder,
                            "3RRS ball balancing platform", ""):
                info = {"name": doc.name}
                try:
                    data_file = doc.dataFile
                    info["id"] = data_file.id
                    info["version"] = data_file.versionNumber
                    info["project"] = data_file.parentProject.name
                    info["project_id"] = data_file.parentProject.id
                except Exception as exc:
                    info["dataFile_error"] = str(exc)
                REPORT["fusion_doc"] = info
                step("cloud save", True,
                     "{0} in {1}".format(doc.name, info.get("project", "?")))
            else:
                step("cloud save", False, "saveAs returned false")
        except Exception as exc:
            step("cloud save", False, str(exc))

        REPORT["ok"] = not REPORT["errors"]
        flush_log()

        # Printed, not a message box. A modal dialog blocks the MCP call that
        # started this and there is nobody to click it.
        print("ball balancer build finished")
        print("steps ok : {0}".format(
            sum(1 for s in REPORT["steps"] if s["ok"])))
        print("errors   : {0}".format(len(REPORT["errors"])))
        print("warnings : {0}".format(len(REPORT["warnings"])))
        for name in REPORT["errors"]:
            print("  error: {0}".format(name))
        print("log      : {0}\\build_log.txt".format(OUT_DIR))

    except Exception:
        REPORT["errors"].append(traceback.format_exc())
        REPORT["ok"] = False
        log("")
        log("FATAL")
        log(traceback.format_exc())
        try:
            flush_log()
        except Exception:
            pass
        # Do not leave a half-built Untitled document behind. Every failed
        # run used to orphan one, and they accumulate in the tab bar.
        if doc is not None:
            try:
                doc.close(False)
            except Exception:
                pass
        del ui
        raise
