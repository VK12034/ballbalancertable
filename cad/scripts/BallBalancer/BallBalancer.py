def crank_angle_rad(r_p, z_p):
    a = r_p - P["base_motor_r"]
    b = z_p - P["motor_shaft_z"]
    l1 = P["crank_len"]
    l2 = P["link2_len"] + P["tie_rod_len"]
    A = 2.0 * a * l1
    B = -2.0 * b * l1
    C = l2 * l2 - l1 * l1 - a * a - b * b
    r = math.hypot(A, B)
    ratio = C / r
    ratio = max(-1.0, min(1.0, ratio))
    return math.atan2(B, A) + math.acos(ratio)


def knee_rz(theta):
    return (P["base_motor_r"] - P["crank_len"] * math.cos(theta),
            P["motor_shaft_z"] + P["crank_len"] * math.sin(theta))


def ball_z(theta):
    kr, kz = knee_rz(theta)
    dr = P["platform_joint_r"] - kr
    l2 = P["link2_len"] + P["tie_rod_len"]
    return kz + math.sqrt(max(0.0, l2 * l2 - dr * dr))


HOME_THETA = math.radians(P["crank_home_angle"])
HOME_Z = ball_z(HOME_THETA)


