ANGLE_PARAMS = {"crank_home_angle", "crank_min_angle", "crank_max_angle"}


def parameters(design):
    created = {}
    user = design.userParameters
    for name, value in P.items():
        unit = "deg" if name in ANGLE_PARAMS else "mm"
        try:
            existing = user.itemByName(name)
            if existing:
                existing.expression = "{0} {1}".format(value, unit)
                created[name] = existing.expression
                continue
            param = user.add(
                name,
                adsk.core.ValueInput.createByString("{0} {1}".format(value, unit)),
                unit,
                PARAM_COMMENTS.get(name, ""))
            created[name] = param.expression
        except Exception as exc:
            warn("parameter {0} not created: {1}".format(name, exc))

    # derived, so the model reports them rather than hiding them in a script
    for name, expression, comment in (
        ("coupler_len", "link2_len + tie_rod_len", "knee to ball centre"),
        ("frame_w", "panel_w + 2 * frame_border", "platform outer, long edge"),
        ("frame_h", "panel_h + 2 * frame_border", "platform outer, short edge"),
    ):
        try:
            if not user.itemByName(name):
                user.add(name, adsk.core.ValueInput.createByString(expression),
                         "mm", comment)
                created[name] = expression
        except Exception as exc:
            warn("derived parameter {0} not created: {1}".format(name, exc))

    REPORT["parameters"] = created
    step("user parameters", len(created) >= len(P),
         "{0} created".format(len(created)))


