def pt(x, y, z=0.0):
    """Point3D from millimetres."""
    return adsk.core.Point3D.create(cm(x), cm(y), cm(z))


def vec(x, y, z):
    return adsk.core.Vector3D.create(x, y, z)


def matrix(origin_mm, x_axis, y_axis, z_axis):
    m = adsk.core.Matrix3D.create()
    m.setWithCoordinateSystem(
        pt(*origin_mm),
        vec(*x_axis), vec(*y_axis), vec(*z_axis),
    )
    return m


def leg_basis(phi_deg):
    """Radial, up and tangential unit vectors for one leg."""
    phi = math.radians(phi_deg)
    radial = (math.cos(phi), math.sin(phi), 0.0)
    up = (0.0, 0.0, 1.0)
    tangent = (math.sin(phi), -math.cos(phi), 0.0)
    return radial, up, tangent


def add(a, b, scale=1.0):
    return (a[0] + b[0] * scale, a[1] + b[1] * scale, a[2] + b[2] * scale)


def new_component(root, name, transform=None):
    occ = root.occurrences.addNewComponent(transform or adsk.core.Matrix3D.create())
    occ.component.name = name
    return occ


def rect(sketch, x0, y0, x1, y1):
    """Centre-independent rectangle by two corners, millimetres."""
    return sketch.sketchCurves.sketchLines.addTwoPointRectangle(
        pt(x0, y0), pt(x1, y1))


def circle(sketch, x, y, dia):
    return sketch.sketchCurves.sketchCircles.addByCenterRadius(
        pt(x, y), cm(dia / 2.0))


def circle_at(sketch, point3d, dia):
    """Circle on a sketch whose plane is not XY, placed by world point."""
    local = sketch.modelToSketchSpace(point3d)
    return sketch.sketchCurves.sketchCircles.addByCenterRadius(local, cm(dia / 2.0))


def extrude(comp, profiles, distance_mm, operation, participants=None,
            start_offset_mm=None):
    """Extrude one or more profiles. Returns the feature."""
    features = comp.features.extrudeFeatures
    if isinstance(profiles, (list, tuple)):
        collection = adsk.core.ObjectCollection.create()
        for prof in profiles:
            collection.add(prof)
        target = collection
    else:
        target = profiles

    inp = features.createInput(target, operation)
    inp.setDistanceExtent(False, adsk.core.ValueInput.createByReal(cm(distance_mm)))
    if participants:
        inp.participantBodies = participants
    if start_offset_mm is not None:
        start = adsk.fusion.OffsetStartDefinition.create(
            adsk.core.ValueInput.createByReal(cm(start_offset_mm)))
        inp.startExtent = start
    return features.add(inp)


def cut_through(comp, profiles, participants, half_mm=80.0):
    """Cut a profile clean through, both directions from the sketch plane.

    A symmetric distance rather than "through all". Through-all refuses with
    "body not found" when the sketch plane lies outside the body it is meant
    to cut, which happens here every time a hole is drawn on a plane that
    only passes near the part. participantBodies keeps the generous extent
    from touching anything else.
    """
    features = comp.features.extrudeFeatures
    if isinstance(profiles, (list, tuple)):
        collection = adsk.core.ObjectCollection.create()
        for prof in profiles:
            collection.add(prof)
        target = collection
    else:
        target = profiles

    inp = features.createInput(target, adsk.fusion.FeatureOperations.CutFeatureOperation)
    inp.setDistanceExtent(True, adsk.core.ValueInput.createByReal(cm(half_mm)))
    if participants:
        inp.participantBodies = participants
    return features.add(inp)


def biggest_profile(sketch):
    """The outer loop, when a sketch has holes inside it."""
    best = None
    best_area = -1.0
    for prof in sketch.profiles:
        try:
            area = prof.areaProperties(
                adsk.fusion.CalculationAccuracy.LowCalculationAccuracy).area
        except Exception:
            continue
        if area > best_area:
            best_area = area
            best = prof
    return best


def all_profiles(sketch):
    return [sketch.profiles.item(i) for i in range(sketch.profiles.count)]


def vertical_plane(comp, phi_deg, name):
    """Construction plane containing the leg's radial line and Z."""
    helper = comp.sketches.add(comp.xYConstructionPlane)
    helper.name = name + "_axis"
    radial, _, _ = leg_basis(phi_deg)
    line = helper.sketchCurves.sketchLines.addByTwoPoints(
        pt(0.0, 0.0, 0.0),
        pt(radial[0] * 150.0, radial[1] * 150.0, 0.0))
    helper.isVisible = False

    planes = comp.constructionPlanes
    inp = planes.createInput()
    inp.setByAngle(line, adsk.core.ValueInput.createByString("90 deg"),
                   comp.xYConstructionPlane)
    plane = planes.add(inp)
    plane.name = name
    return plane


