def build_tie_rod(root, transform):
    """M3 tie rod, 22 mm between ball centres. The spherical freedom."""
    occ = new_component(root, "tie_rod", transform)
    comp = occ.component
    comp.description = "22 mm M3 tie rod with ball ends, bought in"

    sk = comp.sketches.add(comp.xYConstructionPlane)
    sk.name = "rod_axis"
    lines = sk.sketchCurves.sketchLines
    length = P["tie_rod_len"]
    half_d = P["tie_rod_d"] / 2.0

    # revolve a half profile about the X axis
    # The rod is 22 mm between ball centres, but the near ball centre sits
    # inside the coupler's end boss, where the M3 x 8 threads into it. Model
    # only the part that is actually in open air, starting at the boss face,
    # or the rod and the coupler read as interfering when they are simply
    # screwed together.
    boss_r = P["coupler_w"] / 2.0
    axis = lines.addByTwoPoints(pt(0.0, 0.0), pt(length, 0.0))
    lines.addByTwoPoints(pt(boss_r, 0.0), pt(boss_r, half_d))
    lines.addByTwoPoints(pt(boss_r, half_d), pt(length, half_d))
    lines.addByTwoPoints(pt(length, half_d), pt(length, 0.0))

    prof = biggest_profile(sk)
    rev_input = comp.features.revolveFeatures.createInput(
        prof, axis, adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    rev_input.setAngleExtent(False, adsk.core.ValueInput.createByString("360 deg"))
    feat = comp.features.revolveFeatures.add(rev_input)
    body = feat.bodies.item(0)
    body.name = "tie_rod"

    # The ball end. Without it the rod stops dead at the ball centre, flush
    # with the underside of the platform, and nothing sits inside the clevis
    # for the M3 x 35 to pass through. The ball centre stays at tie_rod_len,
    # so the kinematics are unchanged: this only adds the metal that was
    # always meant to be there.
    ball_r = P["tie_rod_ball_d"] / 2.0
    sk_ball = comp.sketches.add(comp.xYConstructionPlane)
    sk_ball.name = "ball_end"
    ball_lines = sk_ball.sketchCurves.sketchLines
    ball_axis = ball_lines.addByTwoPoints(
        pt(length - ball_r, 0.0), pt(length + ball_r, 0.0))
    sk_ball.sketchCurves.sketchArcs.addByThreePoints(
        pt(length - ball_r, 0.0), pt(length, ball_r), pt(length + ball_r, 0.0))

    ball_input = comp.features.revolveFeatures.createInput(
        biggest_profile(sk_ball), ball_axis,
        adsk.fusion.FeatureOperations.JoinFeatureOperation)
    ball_input.participantBodies = [body]
    ball_input.setAngleExtent(False, adsk.core.ValueInput.createByString("360 deg"))
    comp.features.revolveFeatures.add(ball_input)

    step("tie_rod", comp.bRepBodies.count == 1, "")
    return occ


def build_platform(root, transform):
    """platform_frame. Local origin sits in the ball joint plane."""
    occ = new_component(root, "platform_frame", transform)
    comp = occ.component

    frame_w = P["panel_w"] + 2.0 * P["frame_border"]
    frame_h = P["panel_h"] + 2.0 * P["frame_border"]

    sk = comp.sketches.add(comp.xYConstructionPlane)
    sk.name = "frame_outline"
    rect(sk, -frame_w / 2.0, -frame_h / 2.0, frame_w / 2.0, frame_h / 2.0)
    for phi in LEG_PHI:
        a = math.radians(phi)
        circle(sk, P["platform_joint_r"] * math.cos(a),
               P["platform_joint_r"] * math.sin(a), P["ear_r"] * 2.0)

    feat = extrude(comp, all_profiles(sk), P["frame_t"],
                   adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    body = feat.bodies.item(0)
    body.name = "frame"
    for i in range(1, feat.bodies.count):
        warn("platform outline produced an extra body")

    # recess the panel into the top face
    sk_r = comp.sketches.add(comp.xYConstructionPlane)
    sk_r.name = "panel_recess"
    rect(sk_r, -(P["panel_w"] + 0.6) / 2.0, -(P["panel_h"] + 0.6) / 2.0,
         (P["panel_w"] + 0.6) / 2.0, (P["panel_h"] + 0.6) / 2.0)
    extrude(comp, biggest_profile(sk_r), -P["panel_recess"],
            adsk.fusion.FeatureOperations.CutFeatureOperation,
            participants=[body], start_offset_mm=P["frame_t"])

    # window under the panel, so the ribbon can escape and it saves plastic
    sk_w = comp.sketches.add(comp.xYConstructionPlane)
    sk_w.name = "frame_window"
    inner_w = P["panel_w"] - 24.0
    inner_h = P["panel_h"] - 24.0
    rect(sk_w, -inner_w / 2.0, -inner_h / 2.0, inner_w / 2.0, inner_h / 2.0)
    cut_through(comp, biggest_profile(sk_w), [body])

    # Each ear is a clevis: a radial slot splits it into two prongs, the tie
    # rod's ball end sits in the slot, and the M3 x 35 passes through both
    # prongs with an M3 x 5 standoff filling the gap either side. That is the
    # arrangement the source describes for this joint.
    sk_s = comp.sketches.add(comp.xYConstructionPlane)
    sk_s.name = "ear_clevis_slots"
    # Wide enough for the rod's ball end, not just its shaft.
    slot_w = P["tie_rod_ball_d"] + 1.0
    for phi in LEG_PHI:
        a = math.radians(phi)
        cx = P["platform_joint_r"] * math.cos(a)
        cy = P["platform_joint_r"] * math.sin(a)
        radial = (math.cos(a), math.sin(a))
        tangent = (math.sin(a), -math.cos(a))
        lines = sk_s.sketchCurves.sketchLines
        corners = []
        for dr, dt in ((-P["ear_r"] - 2.0, -slot_w / 2.0),
                       (P["ear_r"] + 2.0, -slot_w / 2.0),
                       (P["ear_r"] + 2.0, slot_w / 2.0),
                       (-P["ear_r"] - 2.0, slot_w / 2.0)):
            corners.append((cx + radial[0] * dr + tangent[0] * dt,
                            cy + radial[1] * dr + tangent[1] * dt))
        for i in range(4):
            p0 = corners[i]
            p1 = corners[(i + 1) % 4]
            lines.addByTwoPoints(pt(p0[0], p0[1]), pt(p1[0], p1[1]))
    try:
        cut_through(comp, all_profiles(sk_s), [body])
    except Exception as exc:
        warn("ear clevis slots not cut: {0}".format(exc))

    # M3 x 35 through both prongs of each clevis
    sk_e = comp.sketches.add(comp.xYConstructionPlane)
    sk_e.name = "ear_bores"
    for phi in LEG_PHI:
        a = math.radians(phi)
        circle(sk_e, P["platform_joint_r"] * math.cos(a),
               P["platform_joint_r"] * math.sin(a), P["m3_clear"])
    cut_through(comp, all_profiles(sk_e), [body])

    # retainer clip slots, two per long edge
    sk_c = comp.sketches.add(comp.xYConstructionPlane)
    sk_c.name = "clip_slots"
    for x in (-60.0, 60.0):
        for sign in (-1.0, 1.0):
            inner = sign * (P["panel_h"] / 2.0 + 0.3)
            outer = sign * (P["panel_h"] / 2.0 + 4.3)
            y0, y1 = (inner, outer) if sign > 0.0 else (outer, inner)
            rect(sk_c, x - P["clip_w"] / 2.0, y0, x + P["clip_w"] / 2.0, y1)
    try:
        extrude(comp, all_profiles(sk_c), -3.0,
                adsk.fusion.FeatureOperations.CutFeatureOperation,
                participants=[body], start_offset_mm=P["frame_t"])
    except Exception as exc:
        warn("clip slots not cut: {0}".format(exc))

    step("platform_frame", comp.bRepBodies.count == 1,
         "{0} body, frame {1:.1f} x {2:.1f} mm".format(
             comp.bRepBodies.count, frame_w, frame_h))
    return occ


