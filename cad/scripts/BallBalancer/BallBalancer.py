def check_interference(design, root):
    """Real interference analysis across every occurrence.

    createInterferenceInput and analyzeInterference live on Design, not on
    Component, whatever the shape of the rest of the assembly API suggests.
    """
    try:
        ents = adsk.core.ObjectCollection.create()
        for occ in root.occurrences:
            ents.add(occ)
        inp = design.createInterferenceInput(ents)
        inp.areCoincidentFacesIncluded = False
        results = design.analyzeInterference(inp)

        hits = []
        if results:
            for i in range(results.count):
                res = results.item(i)
                try:
                    volume = res.interferenceBody.volume * 1000.0
                except Exception:
                    volume = None
                hits.append({
                    "a": res.entityOne.name,
                    "b": res.entityTwo.name,
                    "volume_mm3": volume,
                })
        REPORT["interference"] = hits
        step("interference analysis", True,
             "{0} overlapping pairs".format(len(hits)))
        return hits
    except Exception as exc:
        step("interference analysis", False, str(exc))
        return None


def check_kinematics():
    """Travel limits, reach and tilt envelope, recomputed from the model."""
    data = {}
    z_lo = ball_z(math.radians(P["crank_min_angle"]))
    z_hi = ball_z(math.radians(P["crank_max_angle"]))
    data["ball_joint_z_range_mm"] = [z_lo, z_hi]
    data["heave_mm"] = z_hi - z_lo
    data["home_platform_z_mm"] = HOME_Z

    worst = 0.0
    for i in range(201):
        z = z_lo + (z_hi - z_lo) * i / 200.0
        theta = crank_angle_rad(P["platform_joint_r"], z)
        worst = max(worst, abs(ball_z(theta) - z))
    data["ik_round_trip_error_mm"] = worst

    bad = []
    for tilt in range(0, 16):
        for direction in range(0, 360, 15):
            roll = math.radians(tilt) * math.sin(math.radians(direction))
            pitch = math.radians(tilt) * math.cos(math.radians(direction))
            for phi in LEG_PHI:
                a = math.radians(phi)
                x = P["platform_joint_r"] * math.cos(a)
                y = P["platform_joint_r"] * math.sin(a)
                z = HOME_Z - x * math.tan(pitch) + y * math.tan(roll)
                theta = math.degrees(crank_angle_rad(P["platform_joint_r"], z))
                if theta < P["crank_min_angle"] or theta > P["crank_max_angle"]:
                    bad.append([tilt, direction, phi, theta])
    data["tilt_envelope_deg"] = 15
    data["poses_outside_travel"] = len(bad)
    data["first_failures"] = bad[:5]

    deg_per_step = 360.0 / 3200.0
    lift = abs(ball_z(HOME_THETA + math.radians(deg_per_step)) - HOME_Z)
    data["microstep_joint_lift_mm"] = lift
    data["microstep_platform_tilt_deg"] = math.degrees(
        math.atan2(lift, P["platform_joint_r"]))

    REPORT["kinematics"] = data
    ok = worst < 1e-6 and not bad
    step("kinematic envelope", ok,
         "round trip {0:.2e} mm, {1} poses outside travel".format(
             worst, len(bad)))
    return data


def check_actuator_travel(design, root, created, legs):
    """Sweep the cranks and look for collisions away from the home pose.

    Occurrence transforms are rewritten for each pose rather than driven
    through joints, because a closed kinematic loop does not always solve
    when it is assembled by script. The poses come from the same inverse
    kinematics the firmware uses, so what gets checked is what the machine
    will actually do.
    """
    poses = {
        "fully down": math.radians(P["crank_min_angle"]),
        "home": HOME_THETA,
        "fully up": math.radians(P["crank_max_angle"]),
    }
    findings = {}

    names = ("link_1_crank", "link_2_coupler", "tie_rod")
    movers = {}
    for name in names:
        movers[name] = [occ for occ in root.occurrences
                        if occ.component.name == name]

    # Everything carried by the platform has to travel with it. Leaving the
    # panel, ball and clips at the home height makes the legs sweep through a
    # stationary panel and reports collisions the machine does not have.
    PLATFORM_GROUP = ("platform_frame", "touch_panel_8p4", "ball_1in",
                      "retainer_clip")
    riders = []
    for occ in root.occurrences:
        if occ.component.name in PLATFORM_GROUP:
            riders.append((occ, occ.transform2.copy()))

    def place_platform(theta):
        dz = ball_z(theta) - HOME_Z
        for occ, home_matrix in riders:
            moved = home_matrix.copy()
            offset = moved.translation
            offset.z = offset.z + cm(dz)
            moved.translation = offset
            occ.transform2 = moved

    for label, theta in poses.items():
        try:
            new_legs = [leg_transforms(phi, theta) for phi in LEG_PHI]
            for name, key in (("link_1_crank", "crank"),
                              ("link_2_coupler", "coupler"),
                              ("tie_rod", "tie_rod")):
                for occ, leg in zip(movers[name], new_legs):
                    occ.transform2 = leg[key]

            place_platform(theta)

            adsk.doEvents()
            hits = check_interference(design, root)
            findings[label] = {
                "crank_deg": math.degrees(theta),
                "platform_z_mm": ball_z(theta),
                "interference_pairs": len(hits) if hits is not None else None,
                "pairs": hits,
            }
        except Exception as exc:
            findings[label] = {"error": str(exc)}
            warn("pose '{0}' not reached: {1}".format(label, exc))

    # leave it at home
    try:
        home_legs = [leg_transforms(phi, HOME_THETA) for phi in LEG_PHI]
        for name, key in (("link_1_crank", "crank"),
                          ("link_2_coupler", "coupler"),
                          ("tie_rod", "tie_rod")):
            for occ, leg in zip(movers[name], home_legs):
                occ.transform2 = leg[key]
        place_platform(HOME_THETA)
        adsk.doEvents()
    except Exception as exc:
        warn("could not return to home pose: {0}".format(exc))

    REPORT["pose_sweep"] = findings
    reached = sum(1 for v in findings.values() if "error" not in v)
    step("actuator travel sweep", reached == len(poses),
         "{0} of {1} poses reached".format(reached, len(poses)))
    return findings


def check_fastener_access(created):
    """Running clearance at each joint, measured off the tangential stack-up.

    Every number here is a face-to-face distance along the motor axis.
    Negative means two parts occupy the same space; zero means a rotating
    face is flush against a fixed one, which binds just as surely.
    """
    notes = []

    crank_far, crank_near = T_CRANK_HUB      # -16 .. -6, outer face first
    coupler_near = T_COUPLER[0]              # -4
    flange_near = T_FLANGE[1]                # -17.5

    notes.append({
        "fastener": "M4 x 25 knee pivot",
        "note": "coupler inner face to crank arm outer face",
        "clearance_mm": coupler_near - crank_near,
    })
    notes.append({
        "fastener": "M4 x 20 crank clamp",
        "note": "crank hub outer face to flange inner face",
        "clearance_mm": crank_far - flange_near,
    })

    # The shaft has to reach from the motor face all the way across the hub.
    shaft_reach = abs(T_MOTOR_FACE) - abs(crank_near)
    notes.append({
        "fastener": "NEMA 17 shaft engagement in crank hub",
        "note": "shaft is {0} mm long, needs to span {1:.1f} mm".format(
            P["nema_shaft_len"], shaft_reach),
        "clearance_mm": P["nema_shaft_len"] - shaft_reach,
    })
    notes.append({
        "fastener": "M3 x 8 base plate to stand",
        "note": "driven from inside the stand, bolt circle r = {0} mm".format(
            P["stand_bolt_r"]),
        "clearance_mm": P["stand_r"] - P["stand_wall"] - P["stand_bolt_r"],
    })
    REPORT["fastener_access"] = notes
    # Half a millimetre is the smallest gap worth printing and still having.
    tight = [n for n in notes if n["clearance_mm"] is not None
             and n["clearance_mm"] < 0.5]
    step("fastener access", not tight,
         "{0} clearances under 0.5 mm".format(len(tight)))
    return notes


