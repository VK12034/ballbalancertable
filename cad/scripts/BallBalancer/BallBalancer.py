"""Fusion 360 script: build the ball balancer, check it, and export it.

Run from Fusion:

    Utilities -> Scripts and Add-Ins -> Scripts -> BallBalancer -> Run

It creates a NEW design document, so whatever you have open is left alone.
Everything it writes goes to OUT_DIR below. Read build_log.txt first; it
records every step, including the ones that failed.

The machine is a 3RRS parallel manipulator. Three steppers sit on the base
plate with horizontal, tangential axes. Each turns a crank that points inward
at rest. A coupler and an M3 tie rod carry each crank's knee up to one corner
of the platform. Three legs, three rotational inputs, three degrees of
freedom at the platform: heave, roll, pitch.

Geometry is driven by the user parameters created in parameters(). The
in-plane sketch positions are generated from the same numbers by this script,
so the design is regenerated by re-running the script rather than by editing
a dimension and letting the timeline recompute. cad/parameters.md says the
same thing in prose.

Fusion's API is centimetres internally. Anything named *_mm is millimetres and
goes through cm() on the way into the API.
"""

