def export_all(design, root, folder):
    manager = design.exportManager
    written = {}
    for sub in ("source", "step", "mesh", "dxf", "views"):
        os.makedirs(os.path.join(folder, sub), exist_ok=True)

    try:
        path = os.path.join(folder, "source", "BallBalancer.f3d")
        manager.execute(manager.createFusionArchiveExportOptions(path, root))
        written["f3d"] = "source/BallBalancer.f3d"
        step("export f3d", os.path.exists(path), path)
    except Exception as exc:
        step("export f3d", False, str(exc))

    try:
        path = os.path.join(folder, "step", "BallBalancer.step")
        manager.execute(manager.createSTEPExportOptions(path, root))
        written["step"] = "step/BallBalancer.step"
        step("export step", os.path.exists(path), path)
    except Exception as exc:
        step("export step", False, str(exc))

    meshes = []
    for occ in root.occurrences:
        name = occ.component.name
        if name not in PRINTED:
            continue
        if name in meshes:
            continue
        try:
            path = os.path.join(folder, "mesh", name + ".stl")
            options = manager.createSTLExportOptions(occ.component, path)
            options.meshRefinement = \
                adsk.fusion.MeshRefinementSettings.MeshRefinementHigh
            manager.execute(options)
            if os.path.exists(path):
                meshes.append(name)
        except Exception as exc:
            warn("stl for {0} failed: {1}".format(name, exc))
    written["stl"] = ["mesh/{0}.stl".format(n) for n in meshes]
    step("export stl", len(meshes) == len(PRINTED),
         "{0} of {1} printed parts".format(len(meshes), len(PRINTED)))

    # DXF of the flat profiles worth laser cutting or checking on paper
    dxfs = []
    for comp_name, sketch_name in (
        ("base_plate", "plate_outline"),
        ("platform_frame", "frame_outline"),
        ("link_1_crank", "crank_profile"),
        ("link_2_coupler", "coupler_profile"),
    ):
        try:
            for occ in root.occurrences:
                if occ.component.name != comp_name:
                    continue
                sketch = occ.component.sketches.itemByName(sketch_name)
                if not sketch:
                    break
                path = os.path.join(folder, "dxf", comp_name + ".dxf")
                sketch.saveAsDXF(path)
                if os.path.exists(path):
                    dxfs.append(comp_name)
                break
        except Exception as exc:
            warn("dxf for {0} failed: {1}".format(comp_name, exc))
    written["dxf"] = ["dxf/{0}.dxf".format(n) for n in dxfs]
    step("export dxf", len(dxfs) > 0, "{0} profiles".format(len(dxfs)))

    REPORT["exports"] = written
    return written


VIEWS = {
    "iso": (1.0, -1.0, 0.8),
    "front": (0.0, -1.0, 0.0),
    "side": (1.0, 0.0, 0.0),
    "top": (0.0, 0.0, 1.0),
}


def save_views(app, folder):
    viewport = app.activeViewport
    saved = []
    target = adsk.core.Point3D.create(0.0, 0.0, cm(HOME_Z / 2.0))

    for name, direction in VIEWS.items():
        try:
            camera = viewport.camera
            camera.target = target
            distance = 60.0
            camera.eye = adsk.core.Point3D.create(
                target.x + direction[0] * distance,
                target.y + direction[1] * distance,
                target.z + direction[2] * distance)
            camera.upVector = adsk.core.Vector3D.create(0.0, 0.0, 1.0) \
                if name != "top" else adsk.core.Vector3D.create(0.0, 1.0, 0.0)
            camera.isSmoothTransition = False
            viewport.camera = camera
            viewport.fit()
            adsk.doEvents()
            path = os.path.join(folder, "views", name + ".png")
            if viewport.saveAsImageFile(path, 1600, 1200):
                saved.append("views/{0}.png".format(name))
        except Exception as exc:
            warn("view {0} failed: {1}".format(name, exc))

    REPORT["views"] = saved
    step("viewport captures", len(saved) == len(VIEWS),
         "{0} of {1}".format(len(saved), len(VIEWS)))
    return saved


PLA_DENSITY = 1.24      # g/cc, solid PLA
INFILL_FACTOR = 0.38    # walls plus 20% infill, measured off sliced parts

PLA_NAMES = ("PLA", "Polylactide", "ABS Plastic", "Plastic")
STEEL_NAMES = ("Steel", "Steel, Carbon", "Stainless Steel")
GLASS_NAMES = ("Glass", "Acrylic", "ABS Plastic", "Plastic")


def _find_material(app, wanted):
    """First library material matching any of these names."""
    for exact in (True, False):
        for lib in app.materialLibraries:
            try:
                materials = lib.materials
            except Exception:
                continue
            for i in range(materials.count):
                mat = materials.item(i)
                for want in wanted:
                    if exact and mat.name.lower() == want.lower():
                        return mat
                    if not exact and want.lower() in mat.name.lower():
                        return mat
    return None


def assign_materials(app, root):
    """Printed parts in PLA, the ball in steel.

    Without this every mass comes back as if the part were solid steel,
    which makes the printed-part figures useless for working out filament
    or what the platform actually weighs.
    """
    pla = _find_material(app, PLA_NAMES)
    steel = _find_material(app, STEEL_NAMES)
    glass = _find_material(app, GLASS_NAMES)

    mapping = {}
    for name in PRINTED:
        mapping[name] = pla
    mapping["tie_rod"] = steel
    mapping["ball_1in"] = steel
    mapping["nema17_reference"] = steel
    mapping["touch_panel_8p4"] = glass

    applied = 0
    for occ in root.occurrences:
        mat = mapping.get(occ.component.name)
        if mat is None:
            continue
        try:
            for body in occ.component.bRepBodies:
                body.material = mat
            applied += 1
        except Exception as exc:
            warn("material on {0} failed: {1}".format(occ.component.name, exc))

    REPORT["materials"] = {
        "pla": pla.name if pla else None,
        "steel": steel.name if steel else None,
        "panel": glass.name if glass else None,
    }
    step("materials", pla is not None and steel is not None,
         "pla={0} steel={1}".format(pla.name if pla else "none",
                                    steel.name if steel else "none"))


def collect_masses(root):
    rows = []
    seen = set()
    for occ in root.occurrences:
        comp = occ.component
        if comp.name in seen:
            continue
        seen.add(comp.name)
        entry = {"component": comp.name, "bodies": comp.bRepBodies.count}
        try:
            props = comp.getPhysicalProperties(
                adsk.fusion.CalculationAccuracy.HighCalculationAccuracy)
            entry["mass_g"] = props.mass * 1000.0
            entry["volume_mm3"] = props.volume * 1000.0
            # Fusion's stock library has no PLA, so assign_materials settles
            # for ABS at 1.06 g/cc, about 15% light. Volume does not care what
            # material is assigned, so take the printed mass from volume at
            # PLA's real density rather than from whatever matched.
            entry["pla_mass_g"] = props.volume * PLA_DENSITY
            entry["pla_mass_at_20pct_infill_g"] = (
                props.volume * PLA_DENSITY * INFILL_FACTOR)
        except Exception:
            entry["mass_g"] = None
        try:
            box = comp.boundingBox
            entry["size_mm"] = [
                (box.maxPoint.x - box.minPoint.x) * CM,
                (box.maxPoint.y - box.minPoint.y) * CM,
                (box.maxPoint.z - box.minPoint.z) * CM,
            ]
        except Exception:
            entry["size_mm"] = None
        rows.append(entry)
    REPORT["components"] = rows
    step("component inventory", len(rows) > 0, "{0} components".format(len(rows)))
    return rows


